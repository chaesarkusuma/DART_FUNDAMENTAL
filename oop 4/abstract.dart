/**
 * Abstract Class adalah sebuah Class yang tidak dapat dibuat
 * menjadi object (instance) secara langsung.
 *
 * Tetapi dapat digunakan sebagai Class ParentClass (SuperClass)
 * untuk diwariskan kepada class lain.
 *
 * Dengan kata lain:
 * 1. Dapat diwarisi (inheritance)
 * 2. Dapat memiliki properties
 * 3. Dapat memiliki methods
 * 4. Tidak dapat dibuat menjadi object secara langsung
 *
 * Abstract Class dijadikan sebagai kerangka dasar
 * yang akan digunakan oleh class turunannya.
 *
 * Ada kata kunci: abstract
 *
 * Contoh:
 * abstract class NamaClass {}
 */