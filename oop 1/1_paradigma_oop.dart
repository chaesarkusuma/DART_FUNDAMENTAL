/**
 * paradgima adalah pola pikir, kerangka, cara pandang
 * paradigma oop = didasari pada konsep objek yang memiliki
 * atribute serta dapat melakukan operasi atau prosedur tertentu
 * 
 * 4 pilar oop
 * -encapsulation
 * -abstraction
 * -inheritance
 * -polymorphism
 * 
 * => Encapsulation
 * => Ibarat sebuah kantong yang menyimpan sesuatu dalam pemograman
 * => Berfungsi
 * => Mengumpulkan data dan tidak dapat diakses langsung dari luar
 * => Pada kasus "Rizky Ahmad" kita tidak bisa mengubah berat badan dari Rizky
 * tapi kita bisa menambahkannya melalui fungsi / method makan ().
 * 
 * => Abstraction
 * => Bisa dibilang penerapan alami dari encapsulation
 * => Yang mana Abstraction berarti sebuah objek yang hanya
 * menunjukkan operasi secara high-level.
 * => Misalnya kita hanya cukup tau bagaimana Rizky Ahmad makan.
 * => Namun kita tidak perlu bagaimana sistem metabolisme biologis dalam 
 * dalam tubuh si rizky, yang membuat berat badannya bertambah.
 * 
 * => Inheritance
 * => Beberapa objek bisa memiliki beberapa karakteristik atau 
 * perilaku yang sama.
 * => Namun mereka bukanlah objek yang sama
 * => Inheritance pada Rizky Ahmad memiliki sifat dan perilaku yang umum 
 * dengan Manusia lain. seperti berat, warna, tinggi bada, dsb.
 * Maka Rizky Ahmad sebagai objek turunan (Subclass).
 * => Induk classnya disebut (Superclass).
 * 
 * => Polymorphism
 * => "Banyak bentuk"
 * => Objek dapat memiliki bentuk atau implementasi yang berbeda-beda
 * => Pada suatu metode yang sama
 * => Manusia bergerak, akan tetapi cara bergerak cara gerak Rizky Ahmad dengan cara gerak Hikam Ahmad berbeda.
 * itulah yang merupakan contoh dari polymorphism.
 */
